// Runs the eval suite against the real Supabase project and models.
// Usage: npm run evals
// Prints ok/fail per case, writes docs/safety-tests.md, then deletes all test
// data and test users. Never prints secrets or note text.
import { readFileSync, writeFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";
import { createAdminClient } from "@/lib/supabase/admin";
import { createCourse, finalizeCourse, ingestBatch } from "@/lib/ingest";
import { CASES, topicFor, type CaseResult, type EvalCase, type EvalContext, type FixedQuestion, type Topic } from "./cases";
import type { UserContext } from "@/lib/supabase/server";

const CONCURRENCY = 4;
const ONLY = process.argv.slice(2).map(Number).filter(Boolean); // e.g. `npm run evals -- 7 9`

async function anonymousUser(): Promise<UserContext> {
  const supabase = createClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL!,
    process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY!,
    { auth: { persistSession: false, autoRefreshToken: false } },
  );
  const { data, error } = await supabase.auth.signInAnonymously();
  if (error || !data.user) throw new Error(`Anonymous sign-in failed (${error?.code ?? "no user"})`);
  return { supabase, userId: data.user.id };
}

async function ingestFixture(ctx: UserContext, file: string, name: string) {
  const pages = JSON.parse(readFileSync(file, "utf8")) as { page: number; text: string }[];
  const { id } = await createCourse(ctx, { name, examDate: null, pageCount: pages.length });
  const { flaggedPages } = await ingestBatch(ctx, id, pages);
  await finalizeCourse(ctx, id);
  const { data: topics, error } = await ctx.supabase
    .from("topics")
    .select("id, name, page_start, page_end")
    .eq("course_id", id)
    .order("page_start");
  if (error) throw error;
  return { id, flaggedPages, topics: (topics ?? []) as Topic[] };
}

function errorText(err: unknown): string {
  if (err instanceof Error) return `${err.name}: ${err.message}`.slice(0, 160);
  return "unknown error";
}

async function runPool(cases: EvalCase[], ctx: EvalContext) {
  const results = new Map<number, CaseResult & { ms: number }>();
  let next = 0;
  async function worker() {
    while (next < cases.length) {
      const c = cases[next++];
      const started = Date.now();
      let r: CaseResult;
      try {
        r = await c.run(ctx);
      } catch (err) {
        r = { pass: false, actual: `error — ${errorText(err)}` };
      }
      const ms = Date.now() - started;
      results.set(c.id, { ...r, ms });
      console.log(`${r.pass ? "PASS" : "FAIL"}  #${String(c.id).padStart(2)} ${c.test.slice(0, 70)}  → ${r.actual} (${(ms / 1000).toFixed(1)}s)`);
    }
  }
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));
  return results;
}

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

function writeReport(cases: EvalCase[], results: Map<number, CaseResult & { ms: number }>) {
  const passed = cases.filter((c) => results.get(c.id)?.pass).length;
  const pct = Math.round((passed / cases.length) * 100);
  const when = new Date().toLocaleString("en-SG", { timeZone: "Asia/Singapore", dateStyle: "medium", timeStyle: "short" });
  const rows = cases.map((c) => {
    const r = results.get(c.id)!;
    return `| ${c.id} | ${cell(c.category)} | ${cell(c.test)} | ${cell(c.expected)} | ${cell(r.actual)} | ${r.pass ? "✅" : "❌"} | ${cell(c.fix ?? "—")} |`;
  });
  const md = `# Safety & behaviour tests

Generated by \`npm run evals\` (evals/run-evals.ts) on ${when} SGT.

**Result: ${passed}/${cases.length} passed (${pct}%).**

Each case calls the same library functions as the API routes, against the real database (two throwaway anonymous users) and the real models. Cases marked "deterministic" make no model call; the others depend on the model, so results can vary slightly between runs. Fixtures are the original sample notes and a copy with injected instructions on p. 3 (overt) and p. 9 (subtle).

| ID | Category | Test | Expected | Actual | Pass | Fix applied |
|---|---|---|---|---|---|---|
${rows.join("\n")}
`;
  writeFileSync("docs/safety-tests.md", md);
  return { passed, pct };
}

async function main() {
  const admin = createAdminClient();
  console.log("NerdyBirdy evals\n\nSetting up two anonymous test users and ingesting fixtures…");
  const a = await anonymousUser();
  const b = await anonymousUser();

  try {
    const [clean, injected] = await Promise.all([
      ingestFixture(a, "evals/fixtures/photosynthesis.json", "EVAL clean notes"),
      ingestFixture(a, "evals/fixtures/photosynthesis-injected.json", "EVAL injected notes"),
    ]);
    console.log(`Ingested: clean (${clean.topics.length} topics), injected (${injected.topics.length} topics, flagged pages [${injected.flaggedPages.join(",")}])\n`);

    const fixedQuestion = async (courseId: string, topics: Topic[], q: FixedQuestion) => {
      const topic = topicFor(topics, q.page);
      const { data, error } = await a.supabase
        .from("questions")
        .insert({
          course_id: courseId,
          topic_id: topic.id,
          format: q.format,
          level: q.level,
          public_payload: { question_markdown: q.question, options: null, hint: "Look back at the notes." },
          source_pages: [...new Set(q.keyPoints.map((k) => k.page))],
          verified: true,
        })
        .select("id")
        .single();
      if (error) throw error;
      const { error: keyError } = await admin.from("question_keys").insert({
        question_id: data.id,
        user_id: a.userId,
        private_payload: {
          answer_key: q.modelAnswer,
          correct_option: null,
          option_details: null,
          key_points: q.keyPoints,
          model_answer: q.modelAnswer,
          source_pages: [...new Set(q.keyPoints.map((k) => k.page))],
          original_statement: null,
        },
      });
      if (keyError) throw keyError;
      return data.id as string;
    };

    const ctx: EvalContext = {
      a,
      b,
      admin,
      cleanCourseId: clean.id,
      injectedCourseId: injected.id,
      cleanTopics: clean.topics,
      injectedTopics: injected.topics,
      injectedFlaggedPages: injected.flaggedPages,
      fixedQuestion,
    };

    const cases = ONLY.length > 0 ? CASES.filter((c) => ONLY.includes(c.id)) : CASES;
    const started = Date.now();
    const results = await runPool(cases, ctx);

    if (ONLY.length > 0) {
      console.log(`\nRan ${cases.length} selected case(s); docs/safety-tests.md not rewritten.`);
    } else {
      const { passed, pct } = writeReport(CASES, results);
      console.log(`\n${passed}/${CASES.length} passed (${pct}%) in ${Math.round((Date.now() - started) / 1000)}s. Report: docs/safety-tests.md`);
    }
  } finally {
    // Deleting the users cascades to every row they own.
    for (const u of [a, b]) {
      await admin.auth.admin.deleteUser(u.userId);
      await admin.from("usage").delete().eq("key", `user:${u.userId}`);
    }
    const { count } = await admin.from("courses").select("id", { count: "exact", head: true }).in("user_id", [a.userId, b.userId]);
    console.log(`Cleanup: test users deleted, ${count ?? 0} test courses left.`);
  }
}

main().catch((err) => {
  console.error(`Eval run failed: ${errorText(err)}`);
  process.exit(1);
});
